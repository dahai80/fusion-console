package agent

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Per-run provider overrides for CLIs whose own config files outrank the
// process environment:
//
//   - claude: ~/.claude/settings.json `env` beats inherited env, so a host
//     with a global ANTHROPIC_BASE_URL (e.g. a cloud MaaS) would silently
//     ignore the console's forced binding. `--settings <file>` has higher
//     precedence than user settings and applies per invocation.
//   - codex: with ChatGPT-account auth the CLI validates `-m` against the
//     account's models and ignores OPENAI_BASE_URL entirely. A per-run
//     CODEX_HOME with a minimal config.toml pins the custom provider
//     (API-key auth via env_key) without touching the user's ~/.codex.
//
// Both are no-ops when the run carries no matching provider env, and the
// generated files are removed when the run's context ends.

// claudeSettingsOverride writes a settings file with an env block carrying
// the ANTHROPIC_* overrides from env. Returns the path ("" = no override)
// and a cleanup func that is always safe to call.
func claudeSettingsOverride(env map[string]string) (string, func(), error) {
	noop := func() {}
	if env == nil || env["ANTHROPIC_BASE_URL"] == "" {
		return "", noop, nil
	}
	overrides := map[string]string{}
	for k, v := range env {
		if strings.HasPrefix(k, "ANTHROPIC_") {
			overrides[k] = v
		}
	}
	f, err := os.CreateTemp("", "fc-claude-settings-*.json")
	if err != nil {
		return "", noop, fmt.Errorf("claude settings temp file: %w", err)
	}
	err = json.NewEncoder(f).Encode(map[string]any{"env": overrides})
	closeErr := f.Close()
	if err != nil || closeErr != nil {
		os.Remove(f.Name())
		return "", noop, fmt.Errorf("claude settings write: %v", err)
	}
	return f.Name(), func() { os.Remove(f.Name()) }, nil
}

// codexHomeOverride writes a per-run CODEX_HOME whose config.toml pins the
// provider to the injected OPENAI_BASE_URL (chat wire API, API-key auth via
// the OPENAI_API_KEY env). Returns the home dir ("" = no override).
func codexHomeOverride(env map[string]string) (string, func(), error) {
	noop := func() {}
	if env == nil || env["OPENAI_BASE_URL"] == "" || env["OPENAI_API_KEY"] == "" {
		return "", noop, nil
	}
	home, err := os.MkdirTemp("", "fc-codex-home-*")
	if err != nil {
		return "", noop, fmt.Errorf("codex home temp dir: %w", err)
	}
	cfg := fmt.Sprintf(`# generated by fusion-console for this dispatch (per-run CODEX_HOME)
model_provider = "macfabric"

[model_providers.macfabric]
name = "macfabric"
base_url = %q
wire_api = "responses"
env_key = "OPENAI_API_KEY"
`, strings.TrimRight(env["OPENAI_BASE_URL"], "/"))
	if werr := os.WriteFile(filepath.Join(home, "config.toml"), []byte(cfg), 0o600); werr != nil {
		os.RemoveAll(home)
		return "", noop, fmt.Errorf("codex config write: %w", werr)
	}
	return home, func() { os.RemoveAll(home) }, nil
}

// cleanupOnContext removes the generated override when the run's context
// ends (fire-and-forget; the files are in the OS temp dir either way).
func cleanupOnContext(ctx context.Context, cleanup func()) {
	go func() {
		<-ctx.Done()
		cleanup()
	}()
}
