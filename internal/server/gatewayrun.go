// Gateway lifecycle: generate-once config with random secrets, detached
// start, health poll and stop (design v2 §5.2 / plan Phase 2). The console
// owns install+config+start; backends and keys stay on the Gateway page.
package server

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
	"time"

	"github.com/dahai80/fusion-console/internal/config"
)

// gatewayConfigDir is where the console-managed gateway config lives.
func gatewayConfigDir() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".fusion-console", "gateway")
}

func gatewayConfigPath() string { return filepath.Join(gatewayConfigDir(), "config.yaml") }

func gatewayLogPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".fusion-console", "log", "gateway.log")
}

func gatewayPidPath() string { return filepath.Join(gatewayConfigDir(), "gateway.pid") }

// gatewayConfigTemplate mirrors scripts/gateway-config.yaml; the bootstrap
// markers are replaced by per-install random values on first generation.
const gatewayConfigTemplate = `# fusion-gateway config generated by fusion-console (design v2 §5.2).
# Generated once with random secrets; edits here are never overwritten.
server:
    port: 11432
    auto_start:
        enabled: false

auth:
    passthrough: true

admin:
    enabled: true
    jwt_secret: "%s"
    users:
        admin: "%s"
`

// randomHex returns n random bytes hex-encoded.
func randomHex(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		// crypto/rand failing is exceptional; fail loudly rather than writing
		// a predictable secret.
		panic("gatewayrun: crypto/rand unavailable: " + err.Error())
	}
	return hex.EncodeToString(b)
}

// randomPassword returns a URL-safe-ish alphanumeric password.
func randomPassword(n int) string {
	const charset = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKMNPQRSTUVWXYZ23456789"
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic("gatewayrun: crypto/rand unavailable: " + err.Error())
	}
	out := make([]byte, n)
	for i, v := range b {
		out[i] = charset[int(v)%len(charset)]
	}
	return string(out)
}

// ensureGatewayConfig returns the config path, generating it with random
// secrets on first use and storing the admin credentials in the keychain
// (ids gateway-admin-user / gateway-admin-pass — the same ones the Gateway
// admin login card and SSO read). Never overwrites an existing config.
func ensureGatewayConfig() (string, error) {
	path := gatewayConfigPath()
	if _, err := os.Stat(path); err == nil {
		return path, nil // generate-once: user edits are never overwritten
	}
	secret := randomHex(32)
	pass := randomPassword(24)
	body := fmt.Sprintf(gatewayConfigTemplate, secret, pass)
	if err := os.MkdirAll(gatewayConfigDir(), 0o755); err != nil {
		return "", fmt.Errorf("gateway config dir: %w", err)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(body), 0o600); err != nil {
		return "", fmt.Errorf("gateway config write: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return "", fmt.Errorf("gateway config rename: %w", err)
	}
	// Admin credentials into the keychain so "Open Admin GUI" auto-signs.
	// Only fill ids that are not already set — never clobber user-saved ones.
	if user, err := config.GetAPIKey("gateway-admin-user"); err != nil || user == "" {
		_ = config.StoreAPIKey("gateway-admin-user", "admin")
	}
	if p, err := config.GetAPIKey("gateway-admin-pass"); err != nil || p == "" {
		_ = config.StoreAPIKey("gateway-admin-pass", pass)
	}
	return path, nil
}

// startGateway spawns the installed binary detached with the managed config
// and waits for :11432 to answer. A stale pid file is harmless: state is
// port-probe driven.
func startGateway(ctx context.Context) (string, error) {
	bin := gatewayBinaryPath()
	if _, err := os.Stat(bin); err != nil {
		return "", fmt.Errorf("fusion-gateway binary not installed — install it first")
	}
	if gatewayPortOpen(defaultGatewayBase()) {
		return "already running on :11432", nil
	}
	cfgPath, err := ensureGatewayConfig()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(gatewayLogPath()), 0o755); err != nil {
		return "", err
	}
	logF, err := os.OpenFile(gatewayLogPath(), os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		return "", fmt.Errorf("gateway log: %w", err)
	}
	defer logF.Close()
	cmd := exec.Command(bin, "-config", cfgPath)
	cmd.Stdout = logF
	cmd.Stderr = logF
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true} // detach: console restarts don't kill it
	if err := cmd.Start(); err != nil {
		return "", fmt.Errorf("gateway start: %w", err)
	}
	_ = os.WriteFile(gatewayPidPath(), []byte(strconv.Itoa(cmd.Process.Pid)), 0o600)
	// Health poll: 30s budget; on timeout surface the log tail.
	deadline := time.Now().Add(30 * time.Second)
	for time.Now().Before(deadline) {
		select {
		case <-ctx.Done():
			return "", fmt.Errorf("gateway start cancelled")
		default:
		}
		if gatewayPortOpen(defaultGatewayBase()) {
			return fmt.Sprintf("started (pid %d, config %s)", cmd.Process.Pid, cfgPath), nil
		}
		time.Sleep(500 * time.Millisecond)
	}
	return "", fmt.Errorf("gateway did not answer on :11432 within 30s — log tail: %s",
		strings.Join(tailLines(gatewayLogPath(), 20), " | "))
}

// stopGateway terminates the pid-file process (SIGTERM, 5s, SIGKILL).
func stopGateway() (string, error) {
	raw, err := os.ReadFile(gatewayPidPath())
	if err != nil {
		if gatewayPortOpen(defaultGatewayBase()) {
			return "", fmt.Errorf("gateway is running but no pid file exists — stop it manually")
		}
		return "not running", nil
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(raw)))
	if err != nil {
		return "", fmt.Errorf("gateway pid file corrupt: %w", err)
	}
	proc, err := os.FindProcess(pid)
	if err != nil {
		return "not running", nil
	}
	_ = proc.Signal(syscall.SIGTERM)
	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		if !gatewayPortOpen(defaultGatewayBase()) {
			_ = os.Remove(gatewayPidPath())
			return "stopped", nil
		}
		time.Sleep(300 * time.Millisecond)
	}
	_ = proc.Signal(syscall.SIGKILL)
	_ = os.Remove(gatewayPidPath())
	return "stopped (SIGKILL after 5s)", nil
}

// tailLines returns the last n lines of a file, best-effort.
func tailLines(path string, n int) []string {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	lines := strings.Split(strings.TrimRight(string(raw), "\n"), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return lines
}

// handleGatewayStart serves POST /api/gateway/start (start with the managed
// config; installs nothing).
func (s *Server) handleGatewayStart(w http.ResponseWriter, r *http.Request) {
	note, err := startGateway(r.Context())
	if err != nil {
		writeJSON(w, http.StatusBadGateway, map[string]string{"error": err.Error()})
		return
	}
	s.invalidateModelCatalog()
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "note": note})
}

// handleGatewayStop serves POST /api/gateway/stop.
func (s *Server) handleGatewayStop(w http.ResponseWriter, r *http.Request) {
	note, err := stopGateway()
	if err != nil {
		writeJSON(w, http.StatusBadGateway, map[string]string{"error": err.Error()})
		return
	}
	s.invalidateModelCatalog()
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "note": note})
}
