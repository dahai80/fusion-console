#!/usr/bin/env bash
# release-package.sh builds cross-platform release archives for fusion-console.
#
# Each archive contains the console binary and a side-by-side fusion-gateway
# binary (the console auto-starts a bundled gateway when it finds one next to
# its own executable — see bundledGatewayPath in internal/server/gateway.go).
#
# Usage: scripts/release-package.sh vX.Y.Z
# Output: dist/fusion-console-vX.Y.Z-<platform>.tar.gz (zip for Windows) plus
# dist/sha256sums.txt. The fusion-gateway source is expected at
# ../fusion-gateway relative to this repository.
set -euo pipefail

VERSION="${1:?usage: release-package.sh vX.Y.Z}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GATEWAY_ROOT="${GATEWAY_ROOT:-$ROOT/../fusion-gateway}"
OUT="$ROOT/dist/$VERSION"
TARGETS="darwin-amd64 darwin-arm64 linux-amd64 linux-arm64 windows-amd64"

[ -d "$GATEWAY_ROOT/cmd/gateway" ] || { echo "error: fusion-gateway not found at $GATEWAY_ROOT" >&2; exit 1; }
command -v zip >/dev/null || { echo "error: zip is required" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT"

# config.yaml ships in every archive: the gateway refuses to start without
# one and rejects known placeholder secrets, so the template is generated
# per package run with fresh random credentials. Binding stays on 127.0.0.1
# — the shipped secrets are only meaningful on the operator's own machine.
rand() { openssl rand -hex "$1" 2>/dev/null || head -c 64 /dev/urandom | od -An -tx1 | tr -d ' \n' | head -c "$(( $1 * 2 ))"; }
JWT_SECRET="$(rand 24)"
ADMIN_PASS="fc-$(rand 12)"
API_KEY="fg-$(rand 16)"
cat > "$OUT/config.yaml" <<EOF
# fusion-gateway configuration generated by fusion-console release packaging.
# Secrets below are random per package run — rotate them at will.
# Start the gateway from this directory: ./fusion-gateway (reads ./config.yaml).
# Then in fusion-console's wizard, enter these admin credentials:
#   user: admin
#   password: $ADMIN_PASS
server:
    host: "127.0.0.1"
    port: 11432

api_keys:
    - key: "$API_KEY"
      name: "local"
      rpm: 0
      tpm: 0
      allowed_models:
          - "*"

admin:
    enabled: true
    jwt_secret: "$JWT_SECRET"
    users:
        admin: "$ADMIN_PASS"

backends:
    fusion-mlx:
        type: "openai-compatible"
        base_url: "http://127.0.0.1:11434"
        enabled: true
EOF

# Sanity: the generated config must pass the gateway's own validator
# (--check-config), otherwise the whole package ships a gateway that
# cannot boot.
echo "== validating generated config.yaml with gateway --check-config"
CHECK_BIN="$OUT/.check-gateway"
CGO_ENABLED=0 GOOS=darwin GOARCH=arm64 \
    go build -C "$GATEWAY_ROOT" -trimpath -ldflags "-s -w" -o "$CHECK_BIN" ./cmd/gateway
"$CHECK_BIN" --check-config --config "$OUT/config.yaml"
rm -f "$CHECK_BIN"

for t in $TARGETS; do
    goos="${t%-*}"
    goarch="${t#*-}"
    ext=""
    [ "$goos" = "windows" ] && ext=".exe"
    stage="$OUT/.stage/fusion-console-$VERSION-$t"
    mkdir -p "$stage"

    echo "== building console $t"
    CGO_ENABLED=0 GOOS="$goos" GOARCH="$goarch" \
        go build -C "$ROOT" -trimpath -ldflags "-s -w" \
        -o "$stage/fusion-console$ext" ./cmd/console

    echo "== building gateway $t"
    CGO_ENABLED=0 GOOS="$goos" GOARCH="$goarch" \
        go build -C "$GATEWAY_ROOT" -trimpath -ldflags "-s -w" \
        -o "$stage/fusion-gateway$ext" ./cmd/gateway

    cp "$ROOT/README.md" "$stage/"
    cp "$OUT/config.yaml" "$stage/"

    if [ "$goos" = "windows" ]; then
        (cd "$OUT/.stage" && zip -qr "$OUT/fusion-console-$VERSION-$t.zip" "fusion-console-$VERSION-$t")
    else
        tar czf "$OUT/fusion-console-$VERSION-$t.tar.gz" -C "$stage" .
    fi
    echo "== packaged $t"
done

rm -rf "$OUT/.stage"
shasum -a 256 "$OUT"/fusion-console-$VERSION-* > "$OUT/sha256sums.txt"
echo "done: $OUT"
ls -la "$OUT"
